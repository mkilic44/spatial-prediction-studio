.libPaths(c(normalizePath('reference-r/library-extra',winslash='/'),.libPaths()))
library(CAST)
stopifnot(as.character(packageVersion('CAST'))=='1.0.4')
out <- 'tests/fixtures/cast-1.0.4'
dir.create(out,recursive=TRUE,showWarnings=FALSE)
i <- 1:30
train <- data.frame(a=sin(i*.73)+i*.1,b=cos(i*.21)*3,c=(i%%7)^2+.03*i)
pred <- data.frame(a=c(train$a[1],-3,1,7),b=c(train$b[1],4,0,-8),c=c(train$c[1],2,8,50))
test <- lapply(0:4,function(k) which((i-1)%%5==k))
tr <- lapply(test,function(x) setdiff(i,x))
weight <- data.frame(a=1,b=.5,c=2)
di <- trainDI(train=train,weight=weight,CVtrain=tr,CVtest=test,verbose=FALSE)
ans <- aoa(newdata=pred,trainDI=di,verbose=FALSE)
options(digits=17)
write.csv(train,paste0(out,'/aoa_train.csv'),row.names=FALSE)
write.csv(pred,paste0(out,'/aoa_prediction.csv'),row.names=FALSE)
write.csv(data.frame(variable=names(train),weight=unlist(weight),center=di$scaleparam$`scaled:center`,scale=di$scaleparam$`scaled:scale`),paste0(out,'/aoa_parameters.csv'),row.names=FALSE)
write.csv(data.frame(mean_distance=di$trainDist_avrgmean,threshold=di$threshold),paste0(out,'/aoa_summary.csv'),row.names=FALSE)
write.csv(data.frame(fold=(i-1)%%5,di=di$trainDI),paste0(out,'/aoa_train_di.csv'),row.names=FALSE)
write.csv(data.frame(di=ans$DI,applicability=ans$AOA),paste0(out,'/aoa_result.csv'),row.names=FALSE)
xy <- data.frame(x=500000+(i%%6)*17+sin(i)*2,y=4200000+floor(i/6)*19+cos(i)*3)
grid <- expand.grid(x=seq(499900,500240,length.out=15),y=seq(4199900,4200240,length.out=15))
tp <- sf::st_as_sf(xy,coords=c('x','y'),crs=32637)
pp <- sf::st_as_sf(grid,coords=c('x','y'),crs=32637)
set.seed(42)
kn <- knndm(tp,predpoints=pp,k=5,maxp=.5,clustering='hierarchical')
write.csv(xy,paste0(out,'/knndm_train.csv'),row.names=FALSE)
write.csv(grid,paste0(out,'/knndm_prediction.csv'),row.names=FALSE)
fold <- rep(NA_integer_,nrow(xy))
for(j in seq_along(kn$indx_test)) fold[kn$indx_test[[j]]] <- j-1L
write.csv(data.frame(fold=fold,Gj=kn$Gj,Gjstar=kn$Gjstar),paste0(out,'/knndm_train_result.csv'),row.names=FALSE)
write.csv(data.frame(Gij=kn$Gij),paste0(out,'/knndm_prediction_result.csv'),row.names=FALSE)
write.csv(data.frame(k=5,maxp=.5,seed=42,W=kn$W,q=kn$q,CAST='1.0.4'),paste0(out,'/knndm_summary.csv'),row.names=FALSE)
writeLines(capture.output(sessionInfo()),paste0(out,'/session.txt'))
cat('Wrote CAST reference fixtures\n')
